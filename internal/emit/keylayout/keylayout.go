// layoutID is a fixed negative id, required for custom Unicode (group 126) layouts.
const layoutID = -28351

// keyMap indexes, matched by modifierMap below.
const (
	mapBase = iota
	mapShift
	mapCaps
	mapOption
	mapShiftOption
	mapCapsOption
	mapCommand
	mapControl
	mapCount
)

type outputs [mapCount]string

// Emit writes a macOS .keylayout file. Option is the AltGr layer.
func Emit(w io.Writer, keys layout.Keys, name string) error {
	type entry struct {
		code int
		out  outputs
	}

	entries := make([]entry, 0, len(keys)+len(fixedKeys))

	for iso, k := range keys {
		code, err := strconv.Atoi(k.OSXKeycode)
		if err != nil {
			return fmt.Errorf("keylayout: %s: keycode %q: %w", iso, k.OSXKeycode, err)
		}

		out, ok := overrides[iso]
		if ok && k.AltGr != nil {
			return fmt.Errorf("keylayout: %s: altgr not supported, key matches Apple's US layout", iso)
		}
		if !ok {
			out = keyOutputs(k)
		}

		entries = append(entries, entry{code, out})
	}

	for code, s := range fixedKeys {
		var out outputs
		for i := range out {
			out[i] = s
		}
		entries = append(entries, entry{code, out})
	}

	slices.SortFunc(entries, func(a, b entry) int { return a.code - b.code })

	for i := 1; i < len(entries); i++ {
		if entries[i].code == entries[i-1].code {
			return fmt.Errorf("keylayout: key code %d defined twice", entries[i].code)
		}
	}

	var b strings.Builder

	b.WriteString("<?xml version=\"1.1\" encoding=\"UTF-8\"?>\n")
	b.WriteString("<!DOCTYPE keyboard SYSTEM \"file://localhost/System/Library/DTDs/KeyboardLayout.dtd\">\n")
	b.WriteString("<!-- Code generated by ./cmd/trkey. DO NOT EDIT. -->\n")
	fmt.Fprintf(&b, "<keyboard group=\"126\" id=\"%d\" name=\"%s\" maxout=\"1\">\n", layoutID, attr(name))
	b.WriteString(header)

	b.WriteString("    <keyMapSet id=\"ANSI\">\n")
	for i := range mapCount {
		fmt.Fprintf(&b, "        <keyMap index=\"%d\">\n", i)
		for _, e := range entries {
			fmt.Fprintf(&b, "            <key code=\"%d\" output=\"%s\"/>\n", e.code, output(e.out[i]))
		}
		b.WriteString("        </keyMap>\n")
	}
	b.WriteString("    </keyMapSet>\n")
	b.WriteString("</keyboard>\n")

	_, err := io.WriteString(w, b.String())
	return err
}

func keyOutputs(k key.Key) outputs {
	base := k.Base

	var alt key.Layer
	if k.AltGr != nil {
		alt = *k.AltGr
	}

	var o outputs
	o[mapBase] = base.Normal
	o[mapShift] = base.Shift
	o[mapCaps] = capsOf(base)
	o[mapOption] = alt.Normal
	o[mapShiftOption] = alt.Shift
	o[mapCapsOption] = capsOf(alt)
	o[mapCommand] = base.Normal // keep US characters for shortcuts
	o[mapControl] = control(k)

	return o
}

func capsOf(l key.Layer) string {
	if l.Caps {
		return l.Shift
	}
	return l.Normal
}

// control gives Ctrl+letter and Ctrl+[ \ ] their control characters, like Apple's US layout.
func control(k key.Key) string {
	n := k.Base.Normal
	if len(n) == 1 && n[0] >= 'a' && n[0] <= 'z' {
		return string(rune(n[0] - 'a' + 1))
	}

	switch n {
	case "[":
		return "\x1b"
	case "\\":
		return "\x1c"
	case "]":
		return "\x1d"
	}

	return n
}

// output escapes everything except ASCII letters and digits as a character reference.
func output(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' {
			b.WriteRune(r)
		} else {
			fmt.Fprintf(&b, "&#x%04X;", r)
		}
	}
	return b.String()
}

func attr(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "\"", "&quot;")
	return r.Replace(s)
}

// overrides replace a key's outputs on macOS.
// B00 is code 10, which Apple's US layout maps to § ± (on ISO Macs it's the key left of 1).
var overrides = map[string]outputs{
	"B00": {"§", "±", "§", "", "", "", "§", "§"},
}

