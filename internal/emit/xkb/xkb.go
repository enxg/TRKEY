package xkb

import (
	"fmt"
	"io"
	"slices"
	"strings"
	"unicode/utf8"

	"github.com/enxg/TRKEY/internal/key"
	"github.com/enxg/TRKEY/internal/layout"
)

// Emit writes an xkb_symbols file for keys, levels: normal, shift, altgr, shift+altgr.
func Emit(w io.Writer, keys layout.Keys, name string) error {
	var b strings.Builder

	b.WriteString("// Code generated by ./cmd/trkey. DO NOT EDIT.\n\n")
	b.WriteString("default partial alphanumeric_keys\n")
	b.WriteString("xkb_symbols \"basic\" {\n")
	fmt.Fprintf(&b, "    name[Group1] = %q;\n\n", name)

	for _, iso := range sortedISO(keys) {
		if inherited[iso] {
			if keys[iso].AltGr != nil {
				return fmt.Errorf("xkb: %s: altgr not supported, key is inherited from pc", iso)
			}
			continue
		}

		line, err := keyLine(keys[iso])
		if err != nil {
			return fmt.Errorf("xkb: %s: %w", iso, err)
		}
		b.WriteString(line)
	}

	b.WriteString("\n    include \"level3(ralt_switch)\"\n")
	b.WriteString("};\n")

	_, err := io.WriteString(w, b.String())
	return err
}

func keyLine(k key.Key) (string, error) {
	levels := []string{k.Base.Normal, k.Base.Shift}
	var typ string

	switch {
	case k.AltGr == nil && k.Base.Caps:
		typ = "ALPHABETIC"
	case k.AltGr == nil:
		typ = "TWO_LEVEL"
	case k.Base.Caps && k.AltGr.Caps:
		typ = "FOUR_LEVEL_ALPHABETIC"
	case k.Base.Caps:
		typ = "FOUR_LEVEL_SEMIALPHABETIC"
	case k.AltGr.Caps:
		return "", fmt.Errorf("caps on altgr but not on base has no standard xkb type")
	default:
		typ = "FOUR_LEVEL"
	}

	if k.AltGr != nil {
		levels = append(levels, k.AltGr.Normal, k.AltGr.Shift)
	}

	syms := make([]string, len(levels))
	for i, s := range levels {
		sym, err := keysym(s)
		if err != nil {
			return "", err
		}
		syms[i] = sym
	}

	return fmt.Sprintf("    key <%s> { type[Group1] = %q, [ %s ] };\n",
		k.XKB, typ, strings.Join(syms, ", ")), nil
}

// keysym names ASCII so shortcuts keep working, everything else as Unicode.
func keysym(s string) (string, error) {
	if s == "" {
		return "NoSymbol", nil
	}

	r, size := utf8.DecodeRuneInString(s)
	if size != len(s) {
		return "", fmt.Errorf("%q is not a single character", s)
	}

	if name, ok := asciiKeysym[r]; ok {
		return name, nil
	}

	if r < 0x80 && (r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z') {
		return string(r), nil
	}

	if r < 0x20 || r == 0x7f {
		return "", fmt.Errorf("control character %U", r)
	}

	return fmt.Sprintf("U%04X", r), nil
}

// sortedISO orders keys by row (E to A) then column, like a physical keyboard.
func sortedISO(keys layout.Keys) []string {
	isos := make([]string, 0, len(keys))
	for iso := range keys {
		isos = append(isos, iso)
	}

	slices.SortFunc(isos, func(a, b string) int {
		if a[0] != b[0] {
			return int(b[0]) - int(a[0])
		}
		return strings.Compare(a[1:], b[1:])
	})

	return isos
}

// inherited keys are left out so they keep their pc definition, like xkb's own us layout.
// B00 (LSGT, ISO only) gets less/greater/bar/brokenbar from pc.
var inherited = map[string]bool{
	"B00": true,
}

