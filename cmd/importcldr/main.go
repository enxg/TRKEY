package main

import (
	"encoding/xml"
	"os"
	"path/filepath"
	"strings"

	"github.com/enxg/TRKEY/internal/key"
	"github.com/pelletier/go-toml/v2"
)

type Platform struct {
	XMLName xml.Name      `xml:"platform"`
	ID      string        `xml:"id,attr"`
	Maps    []HardwareMap `xml:"hardwareMap>map"`
}

type HardwareMap struct {
	Keycode string `xml:"keycode,attr"`
	ISO     string `xml:"iso,attr"`
}

type Keyboard struct {
	XMLName xml.Name `xml:"keyboard"`
	KeyMaps []KeyMap `xml:"keyMap"`
}

type KeyMap struct {
	Modifiers string       `xml:"modifiers,attr"`
	Keys      []KeyMapping `xml:"map"`
}

type KeyMapping struct {
	ISO string `xml:"iso,attr"`
	To  string `xml:"to,attr"`
}

const CLDR43Dir = "./third_party/cldr-43"

type Keys map[string]key.Key
type ISOKMMap map[string]KeyMapping

func main() {
	var platformWin, platformOSX Platform
	var keyboard Keyboard

	readPlatform("windows", &platformWin)
	readPlatform("osx", &platformOSX)
	readKeyboard(&keyboard)

	keys := make(Keys)

	mapPlatformToKeys(&platformWin, &keys)
	mapPlatformToKeys(&platformOSX, &keys)

	var base KeyMap
	shift := make(ISOKMMap)
	caps := make(ISOKMMap)

	for _, km := range keyboard.KeyMaps {
		var m *ISOKMMap

		switch km.Modifiers {
		case "":
			base = km
		case "shift":
			m = &shift
		case "caps":
			m = &caps
		}

		if m != nil {
			for _, kmp := range km.Keys {
				(*m)[kmp.ISO] = kmp
			}
		}
	}

	for _, k := range base.Keys {
		tk := keys[k.ISO]

		tk.Name = getName(k.ISO, k.To)

		tk.WinVK = getWinVK(k.ISO, k.To)
		tk.XKB = getXKB(k.ISO)

		tk.Base = key.Layer{
			Normal: k.To,
			Shift:  strings.ReplaceAll(shift[k.ISO].To, `\u{22}`, `"`), // CLDR escapes " in en-t-k0-windows
			Caps:   k.To != caps[k.ISO].To,
		}

		keys[k.ISO] = tk
	}

	for iso, k := range keys {
		if k.Base.Normal == "" {
			delete(keys, iso)
		}
	}

	writeOutput(&keys)
}

func readPlatform(name string, p *Platform) {
	f, err := os.ReadFile(filepath.Join(CLDR43Dir, name, "_platform.xml"))
	if err != nil {
		panic(err)
	}

	err = xml.Unmarshal(f, p)
	if err != nil {
		panic(err)
	}
}

func readKeyboard(p *Keyboard) {
	f, err := os.ReadFile(filepath.Join(CLDR43Dir, "windows", "en-t-k0-windows.xml"))
	if err != nil {
		panic(err)
	}

	err = xml.Unmarshal(f, p)
	if err != nil {
		panic(err)
	}
}

func mapPlatformToKeys(platform *Platform, keys *Keys) {
	for _, p := range platform.Maps {
		iso := p.ISO

		if platform.ID == "osx" && iso == "D13" {
			iso = "C12"
		}

		k := (*keys)[iso]
		k.ISO = iso

		switch platform.ID {
		case "windows":
			k.WinScancode = p.Keycode
		case "osx":
			k.OSXKeycode = p.Keycode
		}

		(*keys)[iso] = k
	}
}

func getWinVK(iso, key string) string {
	vk, ok := winVK[iso]

	if ok {
		return vk
	}

	return strings.ToUpper(key)
}

func getXKB(iso string) string {
	xkb, ok := xkbName[iso]

	if ok {
		return xkb
	}

	return "A" + iso
}

func getName(iso, base string) string {
	name, ok := keyName[iso]

	if ok {
		return name
	}

	return base
}

func writeOutput(keys *Keys) {
	const header = "# Code generated by ./cmd/importcldr from CLDR 43. DO NOT EDIT.\n\n"

	outData, err := toml.Marshal(keys)
	if err != nil {
		panic(err)
	}

	err = os.WriteFile("./us.toml", append([]byte(header), outData...), 0666)
	if err != nil {
		panic(err)
	}
}
